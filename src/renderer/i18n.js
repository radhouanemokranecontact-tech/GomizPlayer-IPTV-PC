const I18N = {
  lang: 'ar',
  dir: 'rtl',

  init(lang) {
    this.set(lang || 'en');
  },

  set(lang) {
    const allowed = ['en', 'ar']; // FR removed: only EN/AR are fully translated
    this.lang = allowed.includes(lang) ? lang : 'en';
    this.dir = this.lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = this.lang;
    document.documentElement.dir = this.dir;
    return this.lang;
  },

  t(key, vars) {
    const table = STRINGS[this.lang] || STRINGS.en;
    let value = table[key];
    if (value === undefined) value = STRINGS.en[key];
    if (value === undefined) return key;
    if (vars) {
      for (const name of Object.keys(vars)) {
        value = value.replace(new RegExp('\\{' + name + '\\}', 'g'), String(vars[name]));
      }
    }
    return value;
  },

  locale() {
    if (this.lang === 'ar') return 'ar';
    if (this.lang === 'fr') return 'fr-FR';
    return 'en-GB';
  },

  date(ts) {
    try {
      return new Intl.DateTimeFormat(this.locale(), { hour: '2-digit', minute: '2-digit' }).format(new Date(ts));
    } catch (_) {
      return '';
    }
  },

  day(ts) {
    try {
      return new Intl.DateTimeFormat(this.locale(), { weekday: 'short', day: 'numeric', month: 'short' }).format(new Date(ts));
    } catch (_) {
      return '';
    }
  },

  number(n) {
    try {
      return new Intl.NumberFormat(this.locale()).format(n);
    } catch (_) {
      return String(n);
    }
  },

  /* "5 items" / "5 عناصر" — Arabic uses the plural form for 3–10 and above. */
  plural(key, n) {
    const table = (STRINGS[this.lang] || STRINGS.en).plural || {};
    const pair = table[key] || (STRINGS.en.plural || {})[key] || [key, key];
    return Number(n) === 1 ? pair[0] : pair[1];
  },

  count(n, key) {
    return this.number(n) + ' ' + this.plural(key, n);
  }
};

window.I18N = I18N;
window.t = (key, vars) => I18N.t(key, vars);
window.ltr = (value) => '\u2066' + String(value == null ? '' : value) + '\u2069';

